# Original 16x16 pixel-art generator. It uses category silhouettes first, then flavor palettes.
BG = (0, 0, 0, 0)
INK = (47,  thirty := 30, 27, 255)
WHITE = (238, 231, 202, 255)
GLASS = (174, 207, 199, 255)
HIGHLIGHT = (255, 242, 183, 255)


def new():
    return Image.new("RGBA", (16, 16), BG)


def px(d, x, y, c):
    d.point((x, y), fill=c)


def rect(d, xy, c):
    d.rectangle(xy, fill=c)


def poly(d, pts, c):
    d.polygon(pts, fill=c)


def save(im, name):
    im.save(ROOT / f"{name}.png")


def fruit_blob(name, body, shadow, highlight, stem=(86, 59, 35, 255), leaf=(69, 128, 58, 255), shape="round"):
    im = new(); d = ImageDraw.Draw(im)
    if shape == "round":
        poly(d, [(5,3),(10,3),(12,5),(13,10),(11,13),(5,14),(3,11),(3,6)], shadow)
        poly(d, [(5,4),(10,4),(11,6),(12,10),(10,12),(5,13),(4,10),(4,6)], body)
        rect(d, (5,5,6,7), highlight); rect(d, (7,4,8,5), highlight)
    elif shape == "oval":
        poly(d, [(6,2),(10,3),(12,6),(12,11),(10,14),(6,14),(4,11),(4,6)], shadow)
        poly(d, [(7,3),(10,4),(11,7),(11,11),(9,13),(6,13),(5,10),(5,6)], body)
        rect(d, (6,5,7,8), highlight)
    elif shape == "mango":
        poly(d, [(6,2),(10,3),(12,6),(11,11),(8,14),(5,13),(3,10),(4,5)], shadow)
        poly(d, [(7,3),(10,4),(11,6),(10,10),(8,12),(5,12),(4,9),(5,5)], body)
        rect(d, (6,4,7,7), highlight); rect(d, (8,5,9,5), highlight)
    rect(d, (7,1,8,3), stem)
    poly(d, [(8,2),(11,1),(10,3),(8,3)], leaf)
    save(im, name)


